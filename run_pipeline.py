"""
Runs the whole pipeline, raw data -> charts, in order.

    python run_pipeline.py

(PySpark is separate because it needs Java + the 50K corpus:  python spark/pyspark_text_job.py)
"""
import subprocess
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src"
STEPS = [
    "s01_flatten_json.py",
    "s02_clean_box_office.py",
    "s03_clean_reviews.py",
    "s04_inflation_adjust.py",
    "s05_sentiment_and_themes.py",
    "s06_build_tables.py",
    "s07_analysis_charts.py",
    "s08_radar_framework.py",
]

for step in STEPS:
    print(f"\n===== {step} =====")
    res = subprocess.run([sys.executable, step], cwd=SRC)
    if res.returncode != 0:
        sys.exit(f"{step} failed - fix it before running the next steps")

# one combined cleaning log (the single most important Module 1 evidence)
tables = ROOT / "outputs" / "tables"
parts = sorted(tables.glob("cleaning_log_s*.csv"))
log = pd.concat([pd.read_csv(p) for p in parts], ignore_index=True)
log.insert(0, "id", range(1, len(log) + 1))
log.to_csv(tables / "cleaning_log.csv", index=False)

# markdown copy for the report / GitHub
with open(ROOT / "docs" / "cleaning_log.md", "w", encoding="utf-8") as fh:
    fh.write("# Cleaning log\n\nGenerated by `run_pipeline.py` from the `CleaningLog` entries in each script. "
             "One row per decision: problem found, rows affected, action taken, why.\n\n")
    fh.write("| # | step | dataset | problem | rows | action | why |\n|---|---|---|---|---|---|---|\n")
    for _, r in log.iterrows():
        cells = [str(r[c]).replace("|", "/") for c in ["id", "step", "dataset", "problem", "rows_affected", "action", "reason"]]
        fh.write("| " + " | ".join(cells) + " |\n")
print(f"\ncleaning log: {len(log)} decisions -> outputs/tables/cleaning_log.csv and docs/cleaning_log.md")
print("done. charts in outputs/charts/, tables in outputs/tables/, MySQL CSVs in data/processed/")
